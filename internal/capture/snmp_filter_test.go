package capture

import "testing"

func TestClassifySNMPProbe(t *testing.T) {
	// Minimal SNMPv2c GET sysDescr.0 (community "public")
	probe := []byte{
		0x30, 0x29, 0x02, 0x01, 0x01, 0x04, 0x06, 0x70, 0x75, 0x62, 0x6c, 0x69, 0x63,
		0xa0, 0x1c, 0x02, 0x04, 0x00, 0x00, 0x00, 0x01, 0x02, 0x01, 0x00, 0x02, 0x01, 0x00,
		0x30, 0x0e, 0x30, 0x0c, 0x06, 0x08, 0x2b, 0x06, 0x01, 0x02, 0x01, 0x01, 0x01, 0x00,
		0x05, 0x00,
	}
	name, ok := classifySNMPProbe(probe)
	if !ok || name != "snmp_1_3_6_1_2_1_1_1_0" {
		t.Fatalf("classifySNMPProbe() = (%q, %v), want snmp_1_3_6_1_2_1_1_1_0 true", name, ok)
	}

	// ifTable walk step — filtered out
	ifName := []byte{
		0x30, 0x2c, 0x02, 0x01, 0x01, 0x04, 0x06, 0x70, 0x75, 0x62, 0x6c, 0x69, 0x63,
		0xa1, 0x1f, 0x02, 0x04, 0x00, 0x00, 0x00, 0x02, 0x02, 0x01, 0x00, 0x02, 0x01, 0x00,
		0x30, 0x11, 0x30, 0x0f, 0x06, 0x0b, 0x2b, 0x06, 0x01, 0x02, 0x01, 0x02, 0x02, 0x01, 0x02, 0x01,
		0x05, 0x00,
	}
	if _, ok := classifySNMPProbe(ifName); ok {
		t.Fatal("ifTable OID should be filtered")
	}
}

func TestExtractSNMPRequestOIDs(t *testing.T) {
	oids := extractSNMPRequestOIDs([]byte{
		0x30, 0x29, 0x02, 0x01, 0x01, 0x04, 0x06, 0x70, 0x75, 0x62, 0x6c, 0x69, 0x63,
		0xa0, 0x1c, 0x02, 0x04, 0x00, 0x00, 0x00, 0x01, 0x02, 0x01, 0x00, 0x02, 0x01, 0x00,
		0x30, 0x0e, 0x30, 0x0c, 0x06, 0x08, 0x2b, 0x06, 0x01, 0x02, 0x01, 0x01, 0x03, 0x00,
		0x05, 0x00,
	})
	if len(oids) != 1 || oids[0] != "1.3.6.1.2.1.1.3.0" {
		t.Fatalf("oids = %v, want [1.3.6.1.2.1.1.3.0]", oids)
	}
}